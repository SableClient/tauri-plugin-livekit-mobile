import { readdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const rustCommands = new Set(
  readdirSync(join(root, 'permissions/autogenerated/commands'))
    .filter((name) => name.endsWith('.toml'))
    .map((name) => name.slice(0, -'.toml'.length))
);

const guestJs = readFileSync(join(root, 'guest-js/index.ts'), 'utf8');
const bound = new Set(
  [...guestJs.matchAll(/'plugin:livekit-mobile\|(\w+)'/g)].map((match) => match[1])
);

const missingCommand = [...bound].filter((name) => !rustCommands.has(name)).sort();
const unbound = [...rustCommands].filter((name) => !bound.has(name)).sort();

for (const name of missingCommand) {
  console.error(`guest-js invokes '${name}', which no Rust command provides`);
}
for (const name of unbound) {
  console.error(`Rust command '${name}' has no guest-js binding`);
}

if (missingCommand.length > 0 || unbound.length > 0) process.exit(1);
console.log(`${bound.size} commands bound, matching the Rust surface.`);
